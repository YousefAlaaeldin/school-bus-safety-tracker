// Copies packages/i18n sources into supabase/functions/_shared/i18n/ for the Deno Edge Functions.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const srcDir = join(root, 'packages', 'i18n', 'src');
const outDir = join(root, 'supabase', 'functions', '_shared', 'i18n');

const HEADER = '// GENERATED by pnpm i18n:sync — do not edit\n';

mkdirSync(outDir, { recursive: true });

for (const file of ['en.json', 'ar.json']) {
  copyFileSync(join(srcDir, file), join(outDir, file));
}

for (const file of ['format.ts', 'render.ts']) {
  let text = readFileSync(join(srcDir, file), 'utf8');
  // Deno needs file extensions in relative imports.
  text = text.replace(/from '\.\/format'/g, "from './format.ts'");
  writeFileSync(join(outDir, file), HEADER + text);
}

console.log(`i18n synced to ${outDir}`);
