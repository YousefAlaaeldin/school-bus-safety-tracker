import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = (f: string) => readFileSync(join(root, 'packages', 'i18n', 'src', f), 'utf8');
const out = (f: string) =>
  readFileSync(join(root, 'supabase', 'functions', '_shared', 'i18n', f), 'utf8');

describe('i18n sync (run `pnpm i18n:sync` if this fails)', () => {
  it('copied JSON equals the source', () => {
    expect(JSON.parse(out('en.json'))).toEqual(JSON.parse(src('en.json')));
    expect(JSON.parse(out('ar.json'))).toEqual(JSON.parse(src('ar.json')));
  });

  it('copied TS equals the source apart from header and import extension', () => {
    const strip = (t: string) => t.replace(/^\/\/ GENERATED[^\n]*\n/, '').replace("'./format.ts'", "'./format'");
    expect(strip(out('format.ts'))).toBe(src('format.ts'));
    expect(strip(out('render.ts'))).toBe(src('render.ts'));
  });

  it('has the GENERATED header and the .ts import', () => {
    expect(out('render.ts').startsWith('// GENERATED by pnpm i18n:sync')).toBe(true);
    expect(out('render.ts')).toContain("from './format.ts'");
  });
});
