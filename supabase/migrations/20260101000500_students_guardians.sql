create table public.students (
  id uuid primary key default gen_random_uuid(),
  school_id uuid not null references public.schools (id),
  name_ar text not null,
  name_en text not null,
  grade text,
  photo_path text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.students enable row level security;

create table public.guardian_links (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.students (id),
  school_id uuid not null references public.schools (id),
  guardian_phone text not null,
  guardian_user_id uuid references public.profiles (id) on delete set null,
  relationship text not null default 'guardian'
    check (relationship in ('mother','father','guardian','other')),
  status public.link_status not null default 'pending',
  can_track boolean not null default true,
  approved_by uuid references public.profiles (id) on delete set null,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  unique (student_id, guardian_phone)
);
alter table public.guardian_links enable row level security;

create table public.invite_codes (
  id uuid primary key default gen_random_uuid(),
  guardian_link_id uuid not null references public.guardian_links (id),
  code text not null unique,  -- generated by the RPC, no default
  expires_at timestamptz not null default now() + interval '14 days',
  redeemed_by uuid references public.profiles (id) on delete set null,
  redeemed_at timestamptz,
  created_at timestamptz not null default now()
);
alter table public.invite_codes enable row level security;
